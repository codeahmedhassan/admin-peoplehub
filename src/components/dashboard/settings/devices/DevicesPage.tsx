"use client";

import { useState, useEffect } from "react";
import { deviceApi, ApiError } from "@/lib/api";
import { type Device } from "@/lib/devices";
import DevicesHeader from "./DevicesHeader";
import DevicesTable from "./DevicesTable";
import AddDeviceModal from "./AddDeviceModal";
import ManageUsersModal from "./ManageUsersModal";
import RevokeDeviceDialog from "./RevokeDeviceDialog";
import { useToast, ToastContainer } from "@/components/ui/Toast";

export default function DevicesPage() {
    const { toast, showToast, setToast } = useToast();
    const [devices, setDevices] = useState<Device[]>([]);
    const [loading, setLoading] = useState(true);

    const [addOpen, setAddOpen] = useState(false);
    const [manageDevice, setManageDevice] = useState<Device | null>(null);
    const [revokeDevice, setRevokeDevice] = useState<Device | null>(null);

    // Holds the API key generated by the backend
    const [newRawKey, setNewRawKey] = useState<string | null>(null);

    const loadDevices = async () => {
        try {
            const { devices } = await deviceApi.list();
            setDevices(devices);
        } catch (err) {
            showToast(err instanceof ApiError ? err.message : "Failed to load devices");
        } finally {
            setLoading(false);
        }
    };

    useEffect(() => {
        void loadDevices();
    }, []);

    const handleAdd = async (name: string, location: string) => {
        try {
            const { device } = await deviceApi.create(name, location);
            setNewRawKey(device.apiKey); // This holds the raw key for the modal
            void loadDevices();          // Refresh the table
        } catch (err) {
            showToast(err instanceof ApiError ? err.message : "Failed to create device");
        }
    };

    const handleRevoke = async (device: Device) => {
        try {
            await deviceApi.revoke(device.id);
            void loadDevices();
            setRevokeDevice(null);
        } catch (err) {
            showToast(err instanceof ApiError ? err.message : "Failed to revoke device");
        }
    };

    if (loading) {
        return (
            <div className="flex items-center justify-center py-24">
                <div className="flex items-center gap-3 text-slate-500 text-sm">
                    <div className="w-5 h-5 rounded-full border-2 border-primary/30 border-t-primary animate-spin" />
                    Loading devices…
                </div>
            </div>
        );
    }

    return (
        <div className="flex flex-col gap-6">
            {/* Breadcrumb */}
            <nav className="flex items-center gap-1.5 text-xs font-medium text-slate-400">
                <span className="text-slate-400">Settings</span>
                <span>/</span>
                <span className="text-slate-700 font-semibold">Devices</span>
            </nav>

            <DevicesHeader onAdd={() => setAddOpen(true)} />

            {/* Info banner */}
            <div className="flex items-start gap-3 rounded-2xl bg-blue-50/60 border border-blue-100 p-4">
                <div className="w-8 h-8 rounded-full bg-blue-100 text-blue-600 flex items-center justify-center shrink-0">
                    <svg className="w-4 h-4" fill="none" stroke="currentColor" strokeWidth={2} viewBox="0 0 24 24">
                        <circle cx="12" cy="12" r="10" />
                        <path d="M12 8v4M12 16h.01" strokeLinecap="round" />
                    </svg>
                </div>
                <div className="text-xs leading-relaxed">
                    <p className="font-semibold text-slate-800">
                        About hardware devices
                    </p>
                    <p className="text-slate-500 mt-0.5">
                        Each device gets a unique API key to sync attendance. Keys are shown once —
                        revoke and recreate if lost.
                    </p>
                </div>
            </div>

            <DevicesTable
                devices={devices}
                onManageUsers={(d) => setManageDevice(d)}
                onRevoke={(d) => setRevokeDevice(d)}
            />

            <AddDeviceModal
                open={addOpen}
                onClose={() => {
                    setAddOpen(false);
                    setNewRawKey(null);
                }}
                onSave={handleAdd}
                generatedKey={newRawKey}
            />

            {manageDevice && (
                <ManageUsersModal
                    device={manageDevice}
                    onClose={() => setManageDevice(null)}
                />
            )}

            <RevokeDeviceDialog
                device={revokeDevice}
                onCancel={() => setRevokeDevice(null)}
                onConfirm={() => revokeDevice && handleRevoke(revokeDevice)}
            />
            <ToastContainer toast={toast} onClose={() => setToast(null)} />
        </div>
    );
}